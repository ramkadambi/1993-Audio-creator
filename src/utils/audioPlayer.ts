// Web Audio API and Gemini Audio playback engine for 1993 Madras Audio Drama

let audioCtx: AudioContext | null = null;
let currentSourceNode: AudioBufferSourceNode | null = null;
let analyserNode: AnalyserNode | null = null;
let tapeFilterNode: BiquadFilterNode | null = null;
let ambientGainNode: GainNode | null = null;
let ambientOscillator: OscillatorNode | null = null;

function getAudioContext(): AudioContext {
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
    audioCtx = new AudioContextClass();
  }
  if (audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
  return audioCtx;
}

/**
 * Play authentic 1993 Cassette deck mechanical click sound
 */
export function playCassetteClick(type: 'click' | 'clack' | 'rewind' = 'click') {
  try {
    const ctx = getAudioContext();
    const now = ctx.currentTime;
    
    // Short noise burst for tape head contact
    const bufferSize = ctx.sampleRate * 0.04;
    const noiseBuffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
    const output = noiseBuffer.getChannelData(0);
    for (let i = 0; i < bufferSize; i++) {
      output[i] = (Math.random() * 2 - 1) * Math.exp(-i / (ctx.sampleRate * 0.008));
    }
    
    const noiseSource = ctx.createBufferSource();
    noiseSource.buffer = noiseBuffer;
    
    const filter = ctx.createBiquadFilter();
    filter.type = 'bandpass';
    filter.frequency.setValueAtTime(type === 'rewind' ? 1200 : 2400, now);
    filter.Q.setValueAtTime(3.0, now);
    
    const gain = ctx.createGain();
    gain.gain.setValueAtTime(0.25, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.04);
    
    noiseSource.connect(filter);
    filter.connect(gain);
    gain.connect(ctx.destination);
    
    noiseSource.start(now);
  } catch (e) {
    // AudioContext might be blocked before first user gesture
  }
}

/**
 * Playbase64 audio/wav buffer generated by Gemini TTS
 */
export async function playWavBase64(
  base64Data: string,
  options?: {
    tapeFilter?: boolean;
    pan?: number;
    playbackRate?: number;
    onEnded?: () => void;
  }
): Promise<{ stop: () => void; getVisualLevels: () => { left: number; right: number } }> {
  const ctx = getAudioContext();
  
  // Convert base64 to ArrayBuffer
  const binaryString = window.atob(base64Data);
  const len = binaryString.length;
  const bytes = new Uint8Array(len);
  for (let i = 0; i < len; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }

  const audioBuffer = await ctx.decodeAudioData(bytes.buffer.slice(0));

  // Stop any previous active source
  if (currentSourceNode) {
    try {
      currentSourceNode.stop();
    } catch {}
    currentSourceNode = null;
  }

  const source = ctx.createBufferSource();
  source.buffer = audioBuffer;
  source.playbackRate.value = options?.playbackRate || 1.0;

  // Analyser node for VU meters
  const analyser = ctx.createAnalyser();
  analyser.fftSize = 64;
  analyserNode = analyser;

  // Stereo panner for character acoustic placement
  let panner: StereoPannerNode | null = null;
  if (ctx.createStereoPanner && options?.pan !== undefined) {
    panner = ctx.createStereoPanner();
    panner.pan.value = Math.max(-0.8, Math.min(0.8, options.pan));
  }

  // 1993 Type-I Ferric Cassette tape warmth filter
  let filter: BiquadFilterNode | null = null;
  if (options?.tapeFilter) {
    filter = ctx.createBiquadFilter();
    filter.type = 'lowpass';
    filter.frequency.value = 8800; // Warm analog tape roll-off
    filter.Q.value = 0.7;
    tapeFilterNode = filter;
  }

  // Connect chain
  let lastNode: AudioNode = source;
  if (filter) {
    lastNode.connect(filter);
    lastNode = filter;
  }
  if (panner) {
    lastNode.connect(panner);
    lastNode = panner;
  }

  lastNode.connect(analyser);
  analyser.connect(ctx.destination);

  currentSourceNode = source;

  source.onended = () => {
    if (options?.onEnded) {
      options.onEnded();
    }
  };

  source.start(0);

  const getVisualLevels = () => {
    if (!analyserNode) return { left: 0, right: 0 };
    const data = new Uint8Array(analyserNode.frequencyBinCount);
    analyserNode.getByteFrequencyData(data);
    let sum = 0;
    for (let i = 0; i < data.length; i++) {
      sum += data[i];
    }
    const avg = sum / (data.length * 255);
    const left = Math.min(1, avg * (1 + (options?.pan || 0) * -0.3));
    const right = Math.min(1, avg * (1 + (options?.pan || 0) * 0.3));
    return { left, right };
  };

  const stop = () => {
    try {
      source.stop();
    } catch {}
  };

  return { stop, getVisualLevels };
}

/**
 * Fallback browser SpeechSynthesis in case API key is not yet present
 */
export function playSpeechSynthesisFallback(
  text: string,
  speaker: string,
  options?: { onEnded?: () => void }
): { stop: () => void } {
  if (!('speechSynthesis' in window)) {
    console.warn('SpeechSynthesis not supported');
    options?.onEnded?.();
    return { stop: () => {} };
  }

  window.speechSynthesis.cancel();

  const utterance = new SpeechSynthesisUtterance(text);
  
  // Attempt to find a Tamil voice (ta-IN, ta_IN, ta)
  const voices = window.speechSynthesis.getVoices();
  const tamilVoice = voices.find(
    (v) => v.lang.toLowerCase().includes('ta') || v.lang.toLowerCase().includes('in')
  );
  if (tamilVoice) {
    utterance.voice = tamilVoice;
  }

  // Adjust pitch & rate based on 1993 character roles
  switch (speaker) {
    case 'Arun':
      utterance.pitch = 1.15;
      utterance.rate = 1.1; // energetic, quick
      break;
    case 'Ravi':
      utterance.pitch = 0.95;
      utterance.rate = 0.9; // unhurried, relaxed
      break;
    case 'Priya':
      utterance.pitch = 1.25;
      utterance.rate = 1.05; // sharp, witty
      break;
    case 'Meena':
      utterance.pitch = 1.1;
      utterance.rate = 0.98; // measured, earnest
      break;
    case 'Suresh':
      utterance.pitch = 1.05;
      utterance.rate = 1.2; // dramatic, hurried
      break;
    default:
      utterance.pitch = 1.0;
      utterance.rate = 1.0;
  }

  utterance.onend = () => {
    options?.onEnded?.();
  };

  utterance.onerror = () => {
    options?.onEnded?.();
  };

  window.speechSynthesis.speak(utterance);

  return {
    stop: () => window.speechSynthesis.cancel(),
  };
}

/**
 * Toggle subtle 1993 Madras College ambient background sound (gentle canteen hum)
 */
export function toggleMadrasAmbience(enable: boolean) {
  try {
    const ctx = getAudioContext();
    if (!enable) {
      if (ambientGainNode) {
        ambientGainNode.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 0.5);
        setTimeout(() => {
          try {
            ambientOscillator?.stop();
            ambientOscillator?.disconnect();
          } catch {}
          ambientOscillator = null;
          ambientGainNode = null;
        }, 600);
      }
      return;
    }

    if (ambientGainNode) return;

    // Pink-noise / low-pass filtered college tea stall ambient hum
    const bufferSize = ctx.sampleRate * 2;
    const noiseBuffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
    const data = noiseBuffer.getChannelData(0);
    let b0 = 0, b1 = 0, b2 = 0;
    for (let i = 0; i < bufferSize; i++) {
      const white = Math.random() * 2 - 1;
      b0 = 0.99886 * b0 + white * 0.0555179;
      b1 = 0.99332 * b1 + white * 0.0750759;
      b2 = 0.96900 * b2 + white * 0.1538520;
      data[i] = (b0 + b1 + b2) * 0.08;
    }

    const noiseSource = ctx.createBufferSource();
    noiseSource.buffer = noiseBuffer;
    noiseSource.loop = true;

    const filter = ctx.createBiquadFilter();
    filter.type = 'lowpass';
    filter.frequency.value = 450; // Warm muffled distant tea-stall / college courtyard acoustic

    const gain = ctx.createGain();
    gain.gain.setValueAtTime(0.0001, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.025, ctx.currentTime + 1.0); // very soft

    noiseSource.connect(filter);
    filter.connect(gain);
    gain.connect(ctx.destination);

    noiseSource.start();
    ambientGainNode = gain;
  } catch (err) {
    console.warn('Ambience error:', err);
  }
}
